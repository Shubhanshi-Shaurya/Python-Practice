#LOOPS 
#TYPES OF LOOP - FOR, WHILE, DO-WHILE

#FOR LOOP 
# for i in range(initial value,termination,increment)
for i in range(1,11,1):
    print("hello")


#PRINT ELEMENTS IN A LIST 
list=[10,20,30,40,50]
for i in list:
    print(i)


#WHILE LOOP 
i=2
while i<=6:
    print(i)
    i=i+1

#print odd numbers
for i in range(1,11):
    if(i%2!=0):
        print(i)

#print even numbers
for i in range(1,11):
    if(i%2==0):
        print(i)




